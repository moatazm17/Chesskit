// Get a random Mate in 2 puzzle with progressive difficulty
export const getRandomMateIn2 = (solvedIds: string[]): Puzzle | null => {
  const unsolvedPuzzles = MATE_IN_2_PUZZLES.filter(
    (p) => !solvedIds.includes(p.id)
  );
  if (unsolvedPuzzles.length === 0) return null;

  const sortedPuzzles = [...unsolvedPuzzles].sort((a, b) => a.rating - b.rating);
  const difficultyLevel = Math.floor(solvedIds.length / 5);
  const targetIndex = Math.min(difficultyLevel, sortedPuzzles.length - 1);
  const rangeStart = Math.max(0, targetIndex - 2);
  const rangeEnd = Math.min(sortedPuzzles.length - 1, targetIndex + 3);
  const randomIndex = rangeStart + Math.floor(Math.random() * (rangeEnd - rangeStart + 1));

  return sortedPuzzles[randomIndex];
};


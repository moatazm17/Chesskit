// Get next puzzle based on progressive difficulty
export const getRandomPuzzle = (solvedIds: string[]): Puzzle | null => {
  const unsolvedPuzzles = PUZZLES.filter((p) => !solvedIds.includes(p.id));
  if (unsolvedPuzzles.length === 0) return null;
  
  // Sort by rating (easiest first)
  const sortedPuzzles = [...unsolvedPuzzles].sort((a, b) => a.rating - b.rating);
  
  // Progressive difficulty: as user solves more puzzles, give slightly harder ones
  // Every 5 solved puzzles, skip to a harder puzzle
  const difficultyLevel = Math.floor(solvedIds.length / 5);
  const targetIndex = Math.min(difficultyLevel, sortedPuzzles.length - 1);
  
  // Add some randomness within a range of similar difficulty
  const rangeStart = Math.max(0, targetIndex - 2);
  const rangeEnd = Math.min(sortedPuzzles.length - 1, targetIndex + 3);
  const randomIndex = rangeStart + Math.floor(Math.random() * (rangeEnd - rangeStart + 1));
  
  return sortedPuzzles[randomIndex];
};

// Get daily puzzle (same puzzle for everyone on the same day)
export const getDailyPuzzle = (): Puzzle => {
  const today = new Date();
  const dayOfYear = Math.floor(
    (today.getTime() - new Date(today.getFullYear(), 0, 0).getTime()) /
      (1000 * 60 * 60 * 24)
  );
  const index = dayOfYear % PUZZLES.length;
  return PUZZLES[index];
};

// Get puzzle by rating range
export const getPuzzleByRating = (
  minRating: number,
  maxRating: number,
  solvedIds: string[]
): Puzzle | null => {
  const filtered = PUZZLES.filter(
    (p) =>
      p.rating >= minRating &&
      p.rating <= maxRating &&
      !solvedIds.includes(p.id)
  );
  if (filtered.length === 0) return null;
  return filtered[Math.floor(Math.random() * filtered.length)];
};
